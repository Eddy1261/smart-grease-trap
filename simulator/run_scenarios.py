"""Deterministic scenario runner / replay (Step 7 — Halim Master Audit, §16).

Runs the synthetic S1-S8 scenarios (plus `normal` and `sensor_fault`) through
the real generator + real backend classifier and produces a complete,
reproducible artifact set per scenario:

    metadata.json         scenario metadata (marked synthetic)
    telemetry.jsonl       one JSON record per cycle (deterministic order)
    events.json           derived events (status/FSM/fault transitions)
    actuator_profile.json actuator timeline + summary
    telemetry.csv         CSV schema v1 (Halim -> Risza contract)

IMPORTANT: these are Phase-1 synthetic/replay tests. They are NOT physical
experiments and must never be reported as physical validation.

Usage:
    python -m simulator.run_scenarios --scenario s1_pure_oil --cycles 40 --seed 42
    python -m simulator.run_scenarios --all --cycles 40
    python -m simulator.run_scenarios --replay data/scenarios/s1_pure_oil/telemetry.jsonl
"""
import argparse
import json
import os
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

from backend.app.classifier.status_classifier import StatusClassifier
from backend.app.export.csv_exporter import export_records
from backend.app.schemas.telemetry import TelemetryMessage
from simulator.dummy_publisher import SyntheticTelemetryGenerator
from simulator.scenarios import SCENARIO_PROFILES

# Fixed simulated timeline base so artifacts are byte-deterministic across runs.
SIM_EPOCH = datetime(2026, 1, 1, 0, 0, 0, tzinfo=timezone.utc)

S1_S8_ORDER = [
    "s1_pure_oil",
    "s2_light_emulsion",
    "s3_heavy_emulsion",
    "s4_turbulence",
    "s5_thin_layer",
    "s6_low_temp",
    "s7_peak_load",
    "s8_worst_case",
]

SYNTHETIC_DISCLAIMER = (
    "Synthetic Phase-1 scenario data generated by software simulation. "
    "This is NOT physical experiment validation and must not be reported as such."
)


def _json_dump(path: Path, data: Any) -> None:
    path.write_text(json.dumps(data, indent=2, sort_keys=True), encoding="utf-8")


def generate_records(scenario_key: str, cycles: int, seed: int, dt_seconds: float = 30.0):
    """Generate + classify records deterministically.

    Timestamps use a fixed simulated timeline (SIM_EPOCH + cycle*dt) so the
    artifacts are reproducible byte-for-byte. This is synthetic time, not wall
    clock.
    """
    profile = SCENARIO_PROFILES[scenario_key]
    generator = SyntheticTelemetryGenerator(profile, seed=seed)
    classifier = StatusClassifier()

    records: List[Dict[str, Any]] = []
    for cycle_index in range(cycles):
        msg = generator.generate_next_cycle(dt_seconds=dt_seconds)
        record = json.loads(msg.model_dump_json())
        sim_time = SIM_EPOCH + timedelta(seconds=dt_seconds * cycle_index)
        record["timestamp"] = sim_time.isoformat()
        status = classifier.classify(msg)
        record["system"]["backend_status"] = status.value
        records.append(record)
    return records


def derive_events(records: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Derive deterministic event stream from a record list."""
    events: List[Dict[str, Any]] = []
    prev_status: Optional[str] = None
    prev_fsm: Optional[str] = None
    prev_fault: bool = False
    prev_maintenance: bool = False

    for i, record in enumerate(records, start=1):
        ts = record.get("timestamp")
        status = record.get("system", {}).get("backend_status")
        fsm = record.get("system", {}).get("embedded_state")
        health = record.get("sensors", {}).get("sensor_health", {}) or {}
        fault = bool(record.get("system", {}).get("sensor_fault")) or any(
            health.get(ch, "VALID") != "VALID" for ch in ("ultrasonic", "turbidity", "loadcell")
        )
        maintenance = bool(record.get("system", {}).get("maintenance_required", False))

        if prev_status is not None and status != prev_status:
            events.append({
                "cycle": i, "timestamp": ts, "event_type": "STATUS_TRANSITION",
                "severity": "INFO" if status == "NORMAL" else "WARNING",
                "from": prev_status, "to": status,
            })
        if fsm == "SKIMMING_AKTIF" and prev_fsm != "SKIMMING_AKTIF":
            events.append({"cycle": i, "timestamp": ts, "event_type": "SKIMMING_STARTED", "severity": "INFO"})
        if prev_fsm == "SKIMMING_AKTIF" and fsm != "SKIMMING_AKTIF":
            events.append({"cycle": i, "timestamp": ts, "event_type": "SKIMMING_FINISHED", "severity": "INFO"})
        if fault and not prev_fault:
            events.append({"cycle": i, "timestamp": ts, "event_type": "SENSOR_FAULT", "severity": "ERROR"})
        if status == "PENUH" and prev_status != "PENUH":
            events.append({"cycle": i, "timestamp": ts, "event_type": "CONTAINER_NEAR_FULL", "severity": "WARNING"})
        if maintenance and not prev_maintenance:
            events.append({"cycle": i, "timestamp": ts, "event_type": "MAINTENANCE_REQUIRED", "severity": "WARNING"})

        prev_status, prev_fsm, prev_fault = status, fsm, fault
        prev_maintenance = maintenance

    return events


def build_actuator_profile(records: List[Dict[str, Any]]) -> Dict[str, Any]:
    timeline = []
    motor_on_cycles = 0
    pwm_values = []
    heater_on_cycles = 0
    solenoid_closed_cycles = 0

    for i, record in enumerate(records, start=1):
        actuators = record.get("actuators", {})
        timeline.append({
            "cycle": i,
            "timestamp": record.get("timestamp"),
            "motor_pwm": actuators.get("motor_pwm"),
            "motor_state": actuators.get("motor_state"),
            "heater_state": actuators.get("heater_state"),
            "solenoid_state": actuators.get("solenoid_state"),
            "embedded_state": record.get("system", {}).get("embedded_state"),
        })
        if actuators.get("motor_state") == "ON":
            motor_on_cycles += 1
            pwm_values.append(actuators.get("motor_pwm") or 0)
        if actuators.get("heater_state") == "ON":
            heater_on_cycles += 1
        if actuators.get("solenoid_state") == "CLOSED":
            solenoid_closed_cycles += 1

    return {
        "summary": {
            "total_cycles": len(records),
            "motor_on_cycles": motor_on_cycles,
            "max_motor_pwm": max(pwm_values) if pwm_values else 0,
            "avg_motor_pwm_while_on": (sum(pwm_values) / len(pwm_values)) if pwm_values else 0.0,
            "heater_on_cycles": heater_on_cycles,
            "solenoid_closed_cycles": solenoid_closed_cycles,
        },
        "timeline": timeline,
    }


def write_scenario_artifacts(
    scenario_id: str,
    records: List[Dict[str, Any]],
    output_dir: str,
    metadata: Dict[str, Any],
) -> Dict[str, str]:
    scenario_dir = Path(output_dir) / scenario_id
    scenario_dir.mkdir(parents=True, exist_ok=True)

    events = derive_events(records)
    actuator_profile = build_actuator_profile(records)

    telemetry_path = scenario_dir / "telemetry.jsonl"
    with telemetry_path.open("w", encoding="utf-8") as fh:
        for record in records:
            fh.write(json.dumps(record, sort_keys=True) + "\n")

    _json_dump(scenario_dir / "metadata.json", metadata)
    _json_dump(scenario_dir / "events.json", events)
    _json_dump(scenario_dir / "actuator_profile.json", actuator_profile)

    csv_path = scenario_dir / "telemetry.csv"
    export_records(records, str(csv_path), scenario_id=scenario_id)

    return {
        "directory": str(scenario_dir),
        "metadata": str(scenario_dir / "metadata.json"),
        "telemetry": str(telemetry_path),
        "events": str(scenario_dir / "events.json"),
        "actuator_profile": str(scenario_dir / "actuator_profile.json"),
        "csv": str(csv_path),
    }


def run_scenario(
    scenario_key: str,
    cycles: int = 40,
    seed: int = 42,
    output_dir: str = "data/scenarios",
    dt_seconds: float = 30.0,
) -> Dict[str, Any]:
    profile = SCENARIO_PROFILES[scenario_key]
    records = generate_records(scenario_key, cycles=cycles, seed=seed, dt_seconds=dt_seconds)

    metadata = {
        "scenario_id": scenario_key,
        "scenario_name": profile.name,
        "description": profile.description,
        "synthetic": True,
        "disclaimer": SYNTHETIC_DISCLAIMER,
        "mode": "synthetic",
        "engine": "simulator.dummy_publisher.SyntheticTelemetryGenerator",
        "csv_schema_version": 1,
        "seed": seed,
        "cycles": cycles,
        "dt_seconds": dt_seconds,
        "time_base": SIM_EPOCH.isoformat(),
        "generated_at": datetime.now(timezone.utc).isoformat(),
    }
    artifacts = write_scenario_artifacts(scenario_key, records, output_dir, metadata)
    return {"scenario_id": scenario_key, "seed": seed, "cycles": cycles, "artifacts": artifacts}


def replay_telemetry(
    telemetry_path: str,
    output_dir: str = "data/scenarios",
    scenario_id: str = "replay",
) -> Dict[str, Any]:
    """Replay recorded telemetry through the real classifier and re-export."""
    path = Path(telemetry_path)
    records: List[Dict[str, Any]] = []
    classifier = StatusClassifier()

    with path.open("r", encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            record = json.loads(line)
            msg = TelemetryMessage.model_validate(record)
            status = classifier.classify(msg)
            record["system"]["backend_status"] = status.value
            records.append(record)

    metadata = {
        "scenario_id": scenario_id,
        "synthetic": True,
        "disclaimer": SYNTHETIC_DISCLAIMER,
        "mode": "replay",
        "source": str(path),
        "csv_schema_version": 1,
        "cycles": len(records),
        "generated_at": datetime.now(timezone.utc).isoformat(),
    }
    artifacts = write_scenario_artifacts(scenario_id, records, output_dir, metadata)
    return {"scenario_id": scenario_id, "mode": "replay", "cycles": len(records), "artifacts": artifacts}


def run_all(
    cycles: int = 40,
    seed: int = 42,
    output_dir: str = "data/scenarios",
) -> List[Dict[str, Any]]:
    results = []
    for index, key in enumerate(S1_S8_ORDER):
        results.append(run_scenario(key, cycles=cycles, seed=seed + index, output_dir=output_dir))
    index_path = Path(output_dir) / "index.json"
    _json_dump(index_path, {"runs": results, "generated_at": datetime.now(timezone.utc).isoformat()})
    return results


def main():
    parser = argparse.ArgumentParser(description="Smart Grease Trap deterministic scenario runner (Phase 1, synthetic)")
    parser.add_argument("--scenario", choices=list(SCENARIO_PROFILES.keys()), help="Single scenario key")
    parser.add_argument("--all", action="store_true", help="Run S1-S8")
    parser.add_argument("--replay", metavar="TELEMETRY_JSONL", help="Replay a recorded telemetry.jsonl")
    parser.add_argument("--cycles", type=int, default=40, help="Cycles per scenario")
    parser.add_argument("--seed", type=int, default=42, help="Base random seed")
    parser.add_argument("--output-dir", default=os.path.join("data", "scenarios"), help="Artifact root directory")
    args = parser.parse_args()

    if args.replay:
        result = replay_telemetry(args.replay, output_dir=args.output_dir)
        print(json.dumps(result, indent=2, sort_keys=True))
        return

    if args.all:
        results = run_all(cycles=args.cycles, seed=args.seed, output_dir=args.output_dir)
        for r in results:
            print(f"[+] {r['scenario_id']}: {r['artifacts']['directory']}")
        return

    if not args.scenario:
        parser.error("one of --scenario, --all, or --replay is required")

    result = run_scenario(args.scenario, cycles=args.cycles, seed=args.seed, output_dir=args.output_dir)
    print(json.dumps(result, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
